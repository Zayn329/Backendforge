import {
  CurriculumBlock,
  CurriculumSubBlock,
  LearningMethodology,
  LearningModeAssignment,
} from '../types';

const MODE_MAP: Record<LearningModeAssignment, LearningMethodology[]> = {
  FPT: ['fpt'],
  Recipe: ['recipe'],
  Syntax: ['syntax'],
  'FPT + Recipe': ['fpt', 'recipe'],
  'Concept + Recipe': ['fpt', 'recipe'],
  'FPT + Practical': ['fpt', 'recipe'],
  Practical: ['recipe'],
  'Recipe + Practical': ['recipe'],
  'Concept + Practical': ['fpt', 'recipe'],
};

export function createSubBlock(
  id: string,
  blockId: string,
  order: number,
  title: string,
  learningMode: LearningModeAssignment,
  rawTopics: Array<string | { title: string; group: string }>,
  description?: string
): CurriculumSubBlock {
  return {
    id,
    blockId,
    order,
    title,
    description,
    learningMode,
    requiredModes: MODE_MAP[learningMode],
    topics: rawTopics.map((entry, idx) =>
      typeof entry === 'string'
        ? {
            id: `${id}.${idx + 1}`,
            subBlockId: id,
            order: idx + 1,
            title: entry,
          }
        : {
            id: `${id}.${idx + 1}`,
            subBlockId: id,
            order: idx + 1,
            title: entry.title,
            group: entry.group,
          }
    ),
  };
}

